// ==========================================
// ЗАВДАННЯ 2. РОЗРАХУНОК ВАРТОСТІ
// ==========================================

// Обчислюємо загальну вартість трьох товарів по 2500 грн.
$total = calculateTotal(2500.0, 3);

// ==========================================
// ЗАВДАННЯ 3. FAKER І ЗАМИКАННЯ
// ==========================================

// Створюємо генератор випадкових даних Faker.
$faker = Factory::create();

// Створюємо порожній масив для випадкових цін.
$prices = [];

// Цикл for генерує 10 випадкових цін.
for ($i = 0; $i < 10; $i++) {

    // Випадкова ціна від 1000 до 20000 грн.
    // 2 — кількість знаків після десяткової крапки.
    $prices[] = $faker->randomFloat(2, 1000, 20000);
}

// Встановлюємо мінімальну ціну.
$minThreshold = 5000;

// Фільтруємо масив цін.
$filteredPrices = array_filter(
    $prices,

    // use дозволяє використовувати зовнішню змінну.
    function (float $price) use ($minThreshold): bool {

        // Залишаємо тільки ціни понад 5000 грн.
        return $price > $minThreshold;
    }
);

// ==========================================
// ЗАВДАННЯ 4. ОБРОБКА ВИНЯТКІВ
// ==========================================

try {

    // Пробуємо застосувати неправильну знижку 150%.
    $discountResult = applyDiscount(1000.0, 150.0);

    // Виконується тільки якщо помилки немає.
    $discountMessage = "Ціна зі знижкою: $discountResult грн";

} catch (Exception $e) {

    // Перехоплюємо виняток і отримуємо його повідомлення.
    $discountMessage = 'Помилка: '.$e->getMessage();

} finally {

    // Виконується незалежно від виникнення винятку.
    $discountMessage .= ' Завершення спроби розрахунку.';
}

// ==========================================
// ЗАВДАННЯ 5. ІНДИВІДУАЛЬНИЙ ВАРІАНТ №10
// ==========================================

// ЗАДАЧА 1 (таблиця 3.2, №4)
// Перевірити, чи всі елементи масиву менші за K.

// Створюємо масив цілих чисел.
$numbers = [2, 4, 6, 8, 10];

// Встановлюємо число K.
$k = 15;

// Функція повертає true або false.
$checkResult = areAllLessThanK($numbers, $k);

// ЗАДАЧА 2 (таблиця 3.3, №4)
// Поміняти місцями перше й останнє слово.

// Початковий рядок.
$sentence = 'Магазин продає якісні товари';

// Викликаємо функцію обміну слів.
$swappedSentence = swapFirstLastWords($sentence);

// ЗАДАЧА 3 (таблиця 3.4, №3)
// Перемішати всі слова рядка випадковим чином.

// Початковий рядок.
$originalText = 'Ми створюємо сучасний інтернет магазин';

// Викликаємо функцію перемішування.
$shuffledText = shuffleWords($originalText);

