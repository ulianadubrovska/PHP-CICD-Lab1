<?php

// Створюємо індексний масив із п'яти категорій товарів.
// Індексний масив має числові індекси: 0, 1, 2, 3, 4.
$categories = [
    'Смартфони',
    'Ноутбуки',
    'Планшети',
    'Монітори',
    'Навушники',
];

// Сортуємо масив за зростанням за допомогою sort().
// Після сортування порядок категорій змінюється.
sort($categories);

// Створюємо асоціативний масив одного товару.
// На відміну від індексного, він має іменовані ключі.
$product = [
    'id' => 1,               // Унікальний номер товару
    'name' => 'Ноутбук Lenovo', // Назва товару
    'price' => 25000,        // Ціна товару в гривнях
    'stock' => 10,           // Кількість на складі
    'category_id' => 2,      // Ідентифікатор категорії
];

// Закриваємо PHP, щоб далі написати HTML.
?>

<h2>Завдання 1. Робота з масивами</h2>

<h3>Категорії товарів</h3>

<ul>
    <!-- Перебираємо кожен елемент масиву categories -->
    <?php foreach ($categories as $category) { ?>

        <!-- Виводимо назву категорії у пункті списку -->
        <li><?= htmlspecialchars($category) ?></li>

    <?php } ?>
</ul>

<h3>Інформація про товар</h3>

<ul>
    <!-- Перебираємо ключі та значення масиву product -->
    <?php foreach ($product as $key => $value) { ?>

        <li>
            <!-- Виводимо назву характеристики -->
            <?= htmlspecialchars((string) $key) ?>:

            <!-- Виводимо значення характеристики -->
            <?= htmlspecialchars((string) $value) ?>
        </li>

    <?php } ?>
</ul>
