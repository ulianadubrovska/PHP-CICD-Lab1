<?php

// ЗАВДАННЯ 1. РОБОТА З МАСИВАМИ

// Створюємо індексний масив із п'яти категорій
// інтернет-магазину одягу та аксесуарів.
$categories = [
    'Футболки',
    'Джинси',
    'Сукні',
    'Взуття',
    'Аксесуари',
];

// Сортуємо категорії за допомогою sort().
sort($categories);

// Створюємо асоціативний масив товару Product.
// Поля відповідають UML-діаграмі класів із лабораторної №2.
$product = [
    'id' => 1,                        // Ідентифікатор товару
    'name' => 'Футболка Oversize',     // Назва товару
    'description' => 'Бавовняна футболка вільного крою',
    'price' => 1200,                  // Ціна товару
    'stock' => 12,                    // Кількість на складі
];

?>

<!-- Заголовок першого завдання -->
<h2>Завдання 1. Робота з масивами</h2>

<!-- Виведення категорій одягу та аксесуарів -->
<h3>Категорії одягу та аксесуарів</h3>

<ul>
    <?php foreach ($categories as $category) { ?>
        <li><?= htmlspecialchars($category) ?></li>
    <?php } ?>
</ul>

<!-- Виведення характеристик товару -->
<h3>Інформація про товар</h3>

<ul>
    <?php foreach ($product as $key => $value) { ?>
        <li>
            <?= htmlspecialchars((string) $key) ?>:
            <?= htmlspecialchars((string) $value) ?>
        </li>
    <?php } ?>
</ul>
